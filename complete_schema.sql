-- BUSINESS: Public read, Admin write
DROP POLICY IF EXISTS "Public can read business content" ON public.business;
CREATE POLICY "Public can read business content" ON public.business FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Admins can write business content" ON public.business;
CREATE POLICY "Admins can write business content" ON public.business FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

