-- ------------------------------------------------------------------------------
-- 1. Security Functions
-- ------------------------------------------------------------------------------
-- Defines who is an admin. Since public signup is disabled, any authenticated user
-- is treated as an admin.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT auth.uid() IS NOT NULL;
$$;

-- ------------------------------------------------------------------------------
-- 2. Table Definitions
-- ------------------------------------------------------------------------------

-- BUSINESS
CREATE TABLE IF NOT EXISTS public.business (
  id bigint generated by default as identity primary key,
  name text,
  tagline text,
  description text,
  "aboutTitle" text,
  about text,
  mission text,
  vision text,
  phone text,
  whatsapp text,
  email text,
  address text,
  hours text,
  "footerText" text,
  "socialLinks" jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- CUSTOMERS
CREATE TABLE IF NOT EXISTS public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  address text not null,
  created_at timestamptz not null default now()
);

-- ORDERS
CREATE TABLE IF NOT EXISTS public.orders (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.customers(id) on delete cascade,
  items jsonb not null default '[]'::jsonb,
  total numeric(10, 2) not null,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

-- SHIPPING INFORMATION
CREATE TABLE IF NOT EXISTS public.shipping_information (
  id bigint generated by default as identity primary key,
  order_id bigint references public.orders(id) on delete cascade,
  customer_id bigint references public.customers(id) on delete cascade,
  delivery_partner_name text,
  tracking_link text,
  delivery_date date,
  shipping_date date,
  delivery_status text not null default 'pending',
  created_at timestamptz not null default now()
);

-- CATEGORIES
CREATE TABLE IF NOT EXISTS public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  status text not null default 'active',
  created_at timestamptz not null default now()
);

-- PRODUCTS
CREATE TABLE IF NOT EXISTS public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text,
  categories_id bigint references public.categories(id) on delete set null,
  price numeric(10, 2),
  actual_price numeric(10, 2),
  current_price numeric(10, 2),
  availability boolean not null default true,
  created_at timestamptz not null default now()
);

-- MENUS (Legacy structure)
CREATE TABLE IF NOT EXISTS public.menus (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  actual_price numeric(10, 2),
  current_price numeric(10, 2),
  photo_url text,
  available boolean not null default true,
  created_at timestamptz not null default now()
);

-- GALLERY
CREATE TABLE IF NOT EXISTS public.gallery (
  id bigint generated by default as identity primary key,
  title text,
  description text,
  "imageUrl" text,
  image_url text,
  "mediaType" text default 'image',
  media_type text default 'image',
  "mediaUrl" text,
  media_url text,
  created_at timestamptz not null default now()
);

